drop table if exists arp_send_log cascade;
drop table if exists arp_payments cascade;
drop table if exists arp_invoice_lines cascade;
drop table if exists arp_invoices cascade;
drop table if exists arp_customers cascade;

create table arp_customers (
  id int primary key,
  name text not null,
  contact text,
  email text,
  terms_days int not null default 30,
  kind text
);

create table arp_invoices (
  id int primary key,
  customer_id int references arp_customers(id),
  doc_num text unique not null,
  txn_date date not null,
  due_date date not null,
  amount numeric not null,
  balance numeric not null,
  status text not null,          -- open / paid
  email_status text not null    -- sent / never_sent / bounced
);

create table arp_invoice_lines (
  id int primary key,
  invoice_id int references arp_invoices(id),
  item text not null,
  qty numeric not null,
  rate numeric not null,
  amount numeric not null
);

create table arp_payments (
  id int primary key,
  customer_id int references arp_customers(id),
  invoice_id int references arp_invoices(id),
  date date not null,
  amount numeric not null,
  method text,
  ref text
);

create table arp_send_log (
  id int primary key,
  customer_id int references arp_customers(id),
  kind text not null,            -- statement / invoice
  invoice_id int references arp_invoices(id),
  sent_at date not null,
  to_email text,
  status text not null,          -- delivered / opened / bounced
  subject text
);

alter table arp_customers enable row level security;
