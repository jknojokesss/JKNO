create table roof_customers (
  id int primary key,
  name text not null,
  kind text not null,          -- gc / property_mgmt / owner_direct / institutional / homeowner
  city text,
  state text
);

create table roof_jobs (
  id int primary key,
  job_no text unique not null,
  customer_id int references roof_customers(id),
  name text not null,
  type text not null,           -- commercial / residential / coating
  revenue_class text not null,  -- contract / insurance / maintenance
  state text not null,
  crew text not null,
  pm text not null,
  status text not null,         -- not_started / in_progress / completed
  contract_value numeric not null,
  retainage_pct numeric not null default 0,
  pct_complete numeric not null default 0,  -- production-based, from the field
  signed_date date not null,
  start_date date,
  completion_date date
);

create table roof_worksheets (
  id int primary key,
  job_id int references roof_jobs(id),
  category text not null,       -- material / labor / sub / permit / other
  estimated_cost numeric not null,
  actual_cost numeric not null
);

create table roof_change_orders (
  id int primary key,
  job_id int references roof_jobs(id),
  description text,
  amount numeric not null,
  approved_at date
);

create table roof_supplements (
  id int primary key,
  job_id int references roof_jobs(id),
  description text,
  amount numeric not null,
  status text not null,         -- submitted / approved / billed
  submitted_at date,
  approved_at date
);

create table roof_invoices (
  id int primary key,
  invoice_no text not null,
  job_id int references roof_jobs(id),
  kind text not null,           -- deposit / progress / final / supplement
  amount numeric not null,
  date date not null,
  due_date date not null,
  status text not null,         -- open / paid
  is_insurance boolean not null default false,
  claim_status text             -- adjuster_review / approved / null
);

create table roof_payments (
  id int primary key,
  invoice_id int references roof_invoices(id),
  amount numeric not null,
  date date not null,
  method text
);

create table roof_ap_bills (
  id int primary key,
  job_id int references roof_jobs(id),
  vendor text not null,
  category text not null,       -- material / sub
  amount numeric not null,
  bill_date date not null,
  due_date date not null,
  status text not null          -- open
);

create table roof_gl_summary (
  month date not null,
  account text not null,
  category text not null,       -- revenue / cogs / opex / interest / depreciation
  amount numeric not null,
  primary key (month, account)
);

create table roof_addbacks (
  id int primary key,
  name text not null,
  annual_amount numeric not null,
  justification text not null
);

